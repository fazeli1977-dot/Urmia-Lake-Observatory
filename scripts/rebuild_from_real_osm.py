import osmnx as ox
import geopandas as gpd
from pathlib import Path

# ????? ???? ??? ???? ???????
target_dir = Path('web-dashboard/public/geo')
target_dir.mkdir(parents=True, exist_ok=True)

# ?????? ?????? ?????? ??????
north, south, east, west = 38.0, 37.3, 45.8, 45.0
bbox = (north, south, east, west)

print("Fetching Real Data from OpenStreetMap...")

# ??????? ???????? ????? (?????? ? ????????)
tags_lake = {'water': 'lake', 'natural': 'water'}
tags_causeway = {'infrastructure': 'causeway'}

gdf_lake = ox.features_from_bbox(bbox=bbox, tags=tags_lake)
gdf_causeway = ox.features_from_bbox(bbox=bbox, tags=tags_causeway)

# ????? ?????? ?? ???? ???????
print(f"Saving to {target_dir}")
gdf_lake.to_file(target_dir / 'urmia_lake_boundary.geojson', driver='GeoJSON')
gdf_causeway.to_file(target_dir / 'urmia_causeway.geojson', driver='GeoJSON')

print("Update Complete: Real Data Linked to Web-Dashboard.")
